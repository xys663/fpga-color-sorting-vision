// =============================================================================
// motion_detect.v  ——  帧差法运动目标检测 v6（16x16 块，两级降噪）
// -----------------------------------------------------------------------------
// 对应赛题「高阶挑战项 ④：运动目标检测（帧差法等硬件实现，叠加运动区域提示）」
//
// =============================================================================
// 版本演进（每一版的结论都是现场量出来的，别再走回头路）
// -----------------------------------------------------------------------------
//   v1  单缓冲帧差       -> 依赖"同址读返回旧值"，硬件不成立，满屏红
//   v2  帧奇偶双缓冲     -> 满屏红解决，但 AEC 一动整屏平移，静止也报
//   v3  增益前馈归一化   -> 把差值放大 G^2/256 倍而阈值是常数，暗场景噪声全过
//   v4  检测期间锁死 AEC -> CNT 从 5000+ 降到 1239（屏幕红块 40% -> 8.6%）
//   v5  两帧时间一致性   -> 理论应降到 ~100，现场实测仍是 1259（未收敛）
//   v6  块 8x8 -> 16x16  -> 块内像素从 64 增到 256，噪声再降 2 倍
//   v7  空间连通性门控   -> 左邻或上邻也在动才算，剔除孤立块
//   v8  阈值 18 -> 24     -> 现场夜景（20:12 补拍）实测静止仍有 9~50 块随帧乱跳，
//                            且 50 块那帧越过了 24 的门槛误响了一次。块差分布尾部
//                            比白天厚（暗场数字增益 2x），18 只有约 1.5 sigma，
//                            抬到 24 后静止残余按 p^3 掉到 1 块以内；手挥仍是
//                            108~263 块、块差 40~150，24 有 2 倍以上余量。
//                            同时新增 O_maxd/O_raw 两个"取数"输出，
//                            现场可直接读最大块差，不用再靠截图猜。
//
// -----------------------------------------------------------------------------
// v6 为什么把块放大到 16x16（本轮的核心判断）
// -----------------------------------------------------------------------------
//   现场画面很暗（一根日光灯照桌面），AEC 已经顶到 2.0x 上限，数字增益把
//   传感器噪声一起放大。块均值噪声 sigma 用 v4 的 CNT=1239 反推：
//       p = 1239/14400 = 8.6%，P(|N(0,2s^2)|>13)=0.086 => 13/(1.414s)=1.72
//       => s_block(8x8, 64 像素) = 5.35 LSB  =>  单像素 sigma 约 43 LSB
//   阈值 13 只相当于 2.6 sigma，14400 个块里必然有上千个随机越线。
//   这不是判据写错，是信噪比不够 —— 只能靠"多平均"提高信噪比：
//       块内像素 64 -> 256，噪声按 sqrt(N) 下降 => sigma 减半 -> 2.7 LSB
//   于是同一个阈值 14 从 2.6 sigma 变成 3.7 sigma，误报率从 8.6% 掉到 0.01%。
//   代价：空间分辨率从 8x8 变 16x16（80x45 = 3600 块），红块变大；
//         手是连通大块区域，16x16 完全够用，而且视觉上更醒目。
//
//   第二级降噪（沿用 v5）：连续两帧都超阈值才算运动。
//   噪声帧间独立，p^2 让残余误报再降一个数量级；真实运动连续几十帧都在，
//   只损失 1 帧响应（17ms）。两级叠加后静止时应为 0 块。
//
// -----------------------------------------------------------------------------
// 一、算法
//   1) 降采样成块：1280x720 按 16x16 归并成 80x45 = 3600 块，块值 = 256 像素均值。
//   2) 与上一帧同块均值比较，差 > THRESH 判该块"变了"。
//   3) 连续两帧都"变了"才判定为运动（时间一致性）。
//   4) 运动块涂红，静止块显示灰度；运动块数送 OSD 与蜂鸣器。
//
// 二、块行累加器 acc_ram 为什么这样写（关键，别再改回去）
//   块内 256 个像素在时间上并不连续：块 (bx,by) 分布在 16 个扫描行上，行与行
//   之间隔了另外 79 个块，所以必须按 bx 索引存 80 个部分和（acc_ram）。
//   时序设计成：
//       px==0   : 发起读 acc_ram[bx]  -> 下一拍得到该块前 k-1 行的和 acc_q
//       py==0   : 累加起点，丢弃 acc_q（本帧该块从第 1 行重新算）
//       px==1~15: row_sum 累加本行 16 个像素
//       px==15  : 写入 acc_ram[bx] <= acc_q + row_sum（+当前像素）
//   读(px==0) 与写(px==15) 相差 15 拍，同地址不同拍 => 不依赖存储器读写语义。
//
// 三、资源与时序（相对 v5 全部下降）
//   acc_ram   128x16  = 1 个 eram20k
//   gray_ram  8192x8  = 4 个 eram20k（双缓冲 2 x 4096x8，每 bank 只用 3600）
//   flag_ram  8192x1 / disp_ram 8192x1 = 各 1~2 个
//   DSP：0 个
//   关键路径：8bit 减法 + 9bit 比较，且不在像素主通路上。
// =============================================================================
`timescale 1ns/1ps

module motion_detect #(
    parameter [11:0] H_OFFSET   = 12'd0,      // 有效区左边界
    parameter [11:0] V_OFFSET   = 12'd0,      // 有效区上边界
    parameter [11:0] IMG_WIDTH  = 12'd1280,   // 有效宽（必须是 16 的倍数）
    parameter [11:0] IMG_HEIGHT = 12'd720,    // 有效高（必须是 16 的倍数）
    parameter [7:0]  THRESH     = 8'd24,      // 16x16 块灰度差阈值（LSB）
    parameter [7:0]  CLIP_GRD   = 8'd250,     // 块均值 >= 该值视为削顶，不参与判定
    parameter [15:0] GUARD_CNT  = 16'd2160    // 超过该块数判为"全局突变"（3600 的 60%）
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire        I_pix_en,     // 有效像素（S_window_active）
    input  wire        I_frame,      // 帧起始（I_video_user，只用于块计数清零）
    input  wire        I_en,         // 1 = 曝光已锁定，允许判决（来自 hdmi_mixer）
    input  wire [11:0] I_x,          // 像素坐标（含消隐，用 H_OFFSET 折算）
    input  wire [11:0] I_y,
    input  wire [7:0]  I_gray,       // 灰度输入（gray0）
    output reg         O_motion,     // 当前块是否有运动（1 = 涂红）
    output reg  [15:0] O_cnt,        // 本帧运动块数（实时累加）
    output reg  [15:0] O_cnt_lat,    // 上一帧运动块数（帧起始锁存，给 OSD 稳定显示）
    output wire        O_guard,      // 上一帧判为"全局突变"（不显示红块/不报警）
    // ---- 2026-10-31 新增：现场取数（OSD 显示，用于替代"靠截图猜阈值"）----
    output reg  [7:0]  O_maxd,       // 上一帧出现的最大块差值（LSB，0~255）
    output reg  [15:0] O_raw,        // 上一帧"超过阈值"的块数（未做时间/空间滤波）
    output wire        O_ready       // 上电前几帧未建立历史，输出无效
);

    // -------------------------------------------------------------------------
    // 坐标折算与块网格（16x16）
    // -------------------------------------------------------------------------
    // 消隐期 I_x/I_y 可能小于偏移量，直接相减会下溢成巨大值；
    // 用 I_pix_en 兜底强制回 0，保证地址永远落在合法范围内。
    wire [11:0] rel_x = I_pix_en ? (I_x - H_OFFSET) : 12'd0;
    wire [11:0] rel_y = I_pix_en ? (I_y - V_OFFSET) : 12'd0;

    wire [3:0]  px = rel_x[3:0];        // 块内列 0..15
    wire [3:0]  py = rel_y[3:0];        // 块内行 0..15
    wire [6:0]  bx = rel_x[10:4];       // 块列 0..79
    wire [5:0]  by = rel_y[9:4];        // 块行 0..44

    // blk_addr = by * 80 + bx，80 = 64 + 16，拆成两次左移相加（不占 DSP）
    wire [11:0] a_64 = {6'd0, by} << 6;
    wire [11:0] a_16 = {6'd0, by} << 4;
    wire [11:0] blk_addr = a_64 + a_16 + {5'd0, bx};   // 0..3599

    // 帧有效标志（提前声明：下面的 always 块要用，Verilog 要求先声明后使用）
    reg  [3:0] frm_cnt;
    wire       frame_ok;
    assign     frame_ok = (frm_cnt >= 4'd2) && I_en;

    wire blk_first = (px == 4'd0);      // 块首拍：发起 acc_ram 读
    wire row_end   = (px == 4'd15);     // 每个块在该行的最后一个像素：写回累加器
    wire blk_last  = row_end && (py == 4'd15);  // 块的最后一行最后一点：输出块均值
    wire blk_row0  = (py == 4'd0);      // 块的第一行：摒弃历史，从零累加
    wire wr_en     = I_pix_en && blk_last;
    wire acc_we    = I_pix_en && row_end;

    // -------------------------------------------------------------------------
    // 帧边界
    //   fs_edge：I_frame 上升沿，只用于块计数清零（对时序不敏感）
    //   fs_roll：地址回绕，本帧最后一个有效像素，用于翻转帧奇偶
    //            用它而不是 I_frame，是因为"读到的参考帧到底写没写过"必须
    //            百分之百确定；地址回绕是数据通路自己产生的，骗不了人。
    // -------------------------------------------------------------------------
    reg  frm_d;
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) frm_d <= 1'b0;
        else          frm_d <= I_frame;
    end
    wire fs_edge = I_frame & ~frm_d;

    wire fs_roll = I_pix_en && blk_last &&
                   (rel_x == (IMG_WIDTH  - 12'd1)) &&
                   (rel_y == (IMG_HEIGHT - 12'd1));

    // 帧奇偶：本帧写入 bank=frm_par，读取 bank=~frm_par（上一帧的数据）
    //   两个 bank 在本帧内永不重叠 => 不存在"同一地址同时读写"，
    //   存储器返回值的语义不再影响功能。
    reg frm_par;
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n)       frm_par <= 1'b0;
        else if (fs_roll)   frm_par <= ~frm_par;
    end
    wire [12:0] addr_w = { frm_par, blk_addr};      // 写：本帧 bank
    wire [12:0] addr_r = {~frm_par, blk_addr};      // 读：上一帧 bank

    // -------------------------------------------------------------------------
    // 块行累加器（读在块首、写在块尾，读写相隔 15 拍，不依赖存储器读写语义）
    // -------------------------------------------------------------------------
    reg  [15:0] acc_ram [0:127];        // 按 bx 索引，80 项有效
    reg  [15:0] acc_q;                  // 块首读出的「前 k-1 行部分和」
    reg  [11:0] row_sum;                // 本行已累计的像素和（15 个 8bit 最大 3825）

    always @(posedge I_clk) begin
        if (I_pix_en && blk_first) acc_q <= acc_ram[bx];
    end

    always @(posedge I_clk) begin
        if (!I_pix_en)        row_sum <= 12'd0;
        else if (blk_first)   row_sum <= {4'd0, I_gray};        // 每个块重新起算
        else                  row_sum <= row_sum + {4'd0, I_gray};
    end

    // 块末拍：row_sum 是本行前 15 个像素，加上当前像素正好 16 个
    wire [12:0] row_full = {1'b0, row_sum} + {5'd0, I_gray};
    // 块的第一行不累加历史（否则会把上一帧残留算进来）
    wire [15:0] blk_sum  = blk_row0 ? {3'd0, row_full} : (acc_q + {3'd0, row_full});
    wire [7:0]  blk_avg  = blk_sum[15:8];                      // 256 像素均值

    always @(posedge I_clk) begin
        if (acc_we) acc_ram[bx] <= blk_sum;         // 每行块末写回，实现跨行累加
    end

    // -------------------------------------------------------------------------
    // 双缓冲帧存：gray_ram 存上一帧块均值，flag_ram 存上一帧运动标志
    // -------------------------------------------------------------------------
    reg [7:0] gray_ram [0:8191];
    reg       flag_ram [0:8191];        // 本帧 raw 判定（下一帧当"上帧 raw"读回）
    reg       disp_ram [0:8191];        // 时间一致性滤波后的判定（显示/计数用）
    reg [7:0] g_q;
    reg       f_q;                      // 上一帧 raw 判定
    reg       d_q;                      // 上一帧滤波后判定

    always @(posedge I_clk) begin
        if (wr_en)    gray_ram[addr_w] <= blk_avg;
        if (I_pix_en) g_q <= gray_ram[addr_r];      // 读上一帧 bank，无读写冲突
    end

    // -------------------------------------------------------------------------
    // 逐块帧差（曝光已锁定 => 直接比绝对差）
    //   流水：A 锁存块值 -> B 9bit 减法/比较 -> 写标志 -> 下一帧读出显示
    // -------------------------------------------------------------------------
    reg        wr_d1, wr_d2;
    reg [11:0] addr_d1, addr_d2;
    reg        par_d1,  par_d2;
    reg [7:0]  avg_d1,  gq_d1;
    reg        sat_d1,  sat_d2;
    reg        mov_d1;
    reg        fq_d1;       // 与 mov_d1 同拍的「上一帧同块 raw」
    reg [6:0]  bx_d1, bx_d2;    // 块列号流水（空间连通性判定要用）
    reg [7:0]  maxd_f;          // 本帧最大块差（诊断用）
    reg [15:0] raw_f;           // 本帧超阈值块数（诊断用）

    wire [8:0] bdiff = (avg_d1 >= gq_d1) ? ({1'b0, avg_d1} - {1'b0, gq_d1})
                                         : ({1'b0, gq_d1} - {1'b0, avg_d1});
    // 削顶保护：饱和块与增益/曝光无关，差值为 0 但噪声被压平，判它没意义；
    //   更关键是避免"一半块饱和、一半不饱和"时把曝光跳变误判成运动
    wire       mov_now = (bdiff > {1'b0, THRESH}) & ~sat_d1;

    always @(posedge I_clk) begin
        wr_d1 <= wr_en;
        if (wr_en) begin
            addr_d1 <= blk_addr;
            bx_d1   <= bx;
            par_d1  <= frm_par;
            avg_d1  <= blk_avg;
            gq_d1   <= g_q;
            sat_d1  <= (blk_avg >= CLIP_GRD) | (g_q >= CLIP_GRD);
        end
    end

    always @(posedge I_clk) begin
        if (wr_d1) begin
            mov_d1 <= mov_now;      // 本块判定
            fq_d1  <= f_q;          // 本块「上一帧 raw」：wr_d1 拍 f_q 才还停在本块
        end
        wr_d2   <= wr_d1;
        addr_d2 <= addr_d1;
        bx_d2   <= bx_d1;
        par_d2  <= par_d1;
        sat_d2  <= sat_d1;
    end

    // 时间一致性滤波：连续两帧都判为"变了"才算运动。
    //   噪声帧间独立，两帧同时超阈值的概率是 p^2；真实运动会连续几十帧都在。
    //   注意与 fq_d1 配对而不是直接与 f_q 配对：写 flag 用的是 wr_d2 拍，
    //   那时 addr_r 已经滑到下一块的 px=0，f_q 是隔壁块的标志，会串块。
    wire mov_fil = mov_d1 & fq_d1;

    // -------------------------------------------------------------------------
    // 空间连通性门控（v7 新增，本轮的核心）
    //   现场实测：v6 静止时 MV=118/3600，但按块坐标重建这些红块后统计，
    //   **76 个是完全孤立的单块**（上下左右都没有邻居），只有 63 个连成小片。
    //   真实的手划过时是一整片连通区域，绝不会是一个块孤零零亮一下。
    //   所以判定再加一条：本块要动，**必须左邻或上邻也在动**。
    //     左邻 left_keep：同一块行里刚处理完的那块（一个寄存器）
    //     上邻 row1[bx]  ：上一块行同列的判定（80 位行缓冲，按列写、按列读）
    //   孤立块因此被整片剔除，手所在的大区域完全不受影响。
    // -------------------------------------------------------------------------
    reg [79:0] row1;        // 上一块行每列的判定（固定列索引，不整体移位）
    reg        left_keep;   // 同一块行上一列的判定

    wire up_keep  = row1[bx_d2];
    wire keep     = mov_fil & (left_keep | up_keep);
    wire keep_p   = keep & frame_ok;
    //   邻居缓冲里存的是**门控前**的判定 nb_p，不是 keep_p，这一点必须注意：
    //   若存 keep_p，一片区域的左上角块因"左邻上邻都不动"被剔除后，它右边的块
    //   又失去了左邻，于是整片被从左上一格一格地侵蚀掉（仿真里 2x2 区域会全灭）。
    //   用原始判定做邻居依据，只有真正的"边缘第一块"会被削，区域内部完整保留。
    wire nb_p     = mov_fil & frame_ok;

    //   注意 mov_xx & frame_ok：曝光收敛期（I_en=0）和上电头两帧的判定结果
    //   一律不写进标志 RAM。否则放开判决的第一帧会把这些"假运动"整屏显示出来。
    always @(posedge I_clk) begin
        if (wr_d2) begin
            flag_ram[{par_d2, addr_d2}] <= mov_d1  & frame_ok;
            disp_ram[{par_d2, addr_d2}] <= keep_p;
            row1[bx_d2]  <= nb_p;
            left_keep    <= (bx_d2 == 7'd79) ? 1'b0 : nb_p;
        end
        if (I_pix_en) begin
            f_q <= flag_ram[addr_r];        // 上一帧 raw
            d_q <= disp_ram[addr_r];        // 上一帧滤波后（显示用）
        end
    end

    // -------------------------------------------------------------------------
    // 全局突变保护：上一帧超过 GUARD_CNT 个块都"动" => 判为开灯/关灯/曝光跳变
    // -------------------------------------------------------------------------
    wire guard_now = (O_cnt_lat > GUARD_CNT);
    assign O_guard = guard_now;

    // -------------------------------------------------------------------------
    // 上电屏蔽 + 曝光锁定屏蔽 + 块计数
    //   RAM 初始内容未知，前 2 帧的差值无意义：屏蔽只作用于"输出"和"计数"，
    //   写入照常进行，否则历史值永远建立不起来。
    //   I_en=0（模式 6 刚切进来、曝光还在收敛）期间同样只写不判。
    //   frame_ok / frm_cnt 已在文件上方声明（供标志写入处使用）。
    // -------------------------------------------------------------------------
    assign    O_ready  = frame_ok;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            frm_cnt   <= 4'd0;
            O_cnt     <= 16'd0;
            O_cnt_lat <= 16'd0;
            O_maxd    <= 8'd0;
            O_raw     <= 16'd0;
            maxd_f    <= 8'd0;
            raw_f     <= 16'd0;
        end else if (fs_edge) begin
            if (frm_cnt != 4'd15) frm_cnt <= frm_cnt + 4'd1;
            O_cnt_lat <= O_cnt;           // 锁存上一帧结果，供 OSD 稳定显示
            O_maxd    <= maxd_f;          // 上一帧的最大块差 / 超阈值块数
            O_raw     <= raw_f;
            maxd_f    <= 8'd0;
            raw_f     <= 16'd0;
            O_cnt     <= 16'd0;
        end else if (wr_d1) begin
            // 诊断量都取"滤波前"的值，才反映判据本身还有多少余量
            if (bdiff > {1'b0, maxd_f}) maxd_f <= bdiff[7:0];
            if (mov_now)                raw_f  <= raw_f + 16'd1;
        end else if (wr_d2 && keep_p) begin
            O_cnt <= O_cnt + 16'd1;
        end
    end

    // -------------------------------------------------------------------------
    // 运动标志输出（d_q 已延迟 1 拍，这里再打 1 拍 = 共 2 拍）
    //   全局突变时强制不出红块：宁可这一帧不报，也不要满屏红 + 长鸣
    // -------------------------------------------------------------------------
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n)      O_motion <= 1'b0;
        else if (I_pix_en) O_motion <= d_q & frame_ok & ~guard_now;
